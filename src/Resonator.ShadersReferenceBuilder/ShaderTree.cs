using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.Json;

namespace Resonator.ShadersReferenceBuilder;

/// <summary>
/// The unpacked reference tree and the metadata table generated from it.
///
///   &lt;tree&gt;/&lt;version&gt;/&lt;Shader&gt;/metadata.json + Sources/**     version "_" = current, otherwise dated
///
/// The table is a partial class whose AddGeneratedMeta lists, per shader version,
/// (version, shader, sourceFile.filename, sourceFile.hash, uniqueKeywords); bit i of a variant =
/// keyword i. The consumer's hand-written half of the class reads it.
/// </summary>
internal static class ShaderTree
{
    /// <summary>Rebuild the tree from the cache: each listed shader's bundle is unpacked, a cache dir
    /// with a hand-prepared metadata.json (and no bundle) is copied. Returns the number missing.</summary>
    public static int Unpack(string cache, List<OfficialShader> listed, string tree, TextWriter log)
    {
        if (Directory.Exists(tree)) Directory.Delete(tree, recursive: true);
        int unpacked = 0, copied = 0, missing = 0;
        foreach (var s in listed)
        {
            string src = Path.Combine(cache, s.Version, s.Shader);
            string dest = Path.Combine(tree, s.Version, s.Shader);
            string bundle = Path.Combine(src, s.FileName);
            if (File.Exists(bundle)) { ShaderBundle.Unpack(bundle, dest); unpacked++; }
            else if (File.Exists(Path.Combine(src, "metadata.json"))) { CopyDir(src, dest); copied++; }
            else { missing++; log.WriteLine($"  missing: {s.Version}/{s.Shader} (no bundle or metadata.json in the cache)"); }
        }
        log.WriteLine($"unpacked {unpacked} bundle(s), copied {copied} prepared dir(s), {missing} missing -> {tree}");
        return missing;
    }

    static void CopyDir(string src, string dest)
    {
        foreach (string f in Directory.EnumerateFiles(src, "*", SearchOption.AllDirectories))
        {
            if (ShaderBundle.IsBundle(f)) continue;
            string d = Path.Combine(dest, Path.GetRelativePath(src, f));
            Directory.CreateDirectory(Path.GetDirectoryName(d)!);
            File.Copy(f, d, overwrite: true);
        }
    }

    /// <summary>Write the metadata table for the tree. Returns the number of entries.</summary>
    public static int WriteMeta(string tree, string ns, string cls, string outFile)
    {
        var entries = Collect(tree);
        if (entries.Count == 0)
            throw new Exception("no <version>/<Shader>/metadata.json under " + tree);
        Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(outFile))!);
        File.WriteAllText(outFile, Render(entries, ns, cls), new UTF8Encoding(false));
        return entries.Count;
    }

    record Entry(string Version, string Shader, string File, string Hash, string[] Keywords);

    static List<Entry> Collect(string root)
    {
        var entries = new List<Entry>();
        foreach (string vdir in Directory.GetDirectories(root).OrderBy(Path.GetFileName, StringComparer.Ordinal))
            foreach (string sdir in Directory.GetDirectories(vdir).OrderBy(Path.GetFileName, StringComparer.Ordinal))
            {
                string path = Path.Combine(sdir, "metadata.json");
                if (!File.Exists(path)) continue;
                try
                {
                    using var doc = JsonDocument.Parse(File.ReadAllText(path));   // ReadAllText drops a BOM
                    var src = doc.RootElement.GetProperty("sourceFile");
                    string Str(JsonElement e, string k) =>
                        e.TryGetProperty(k, out var v) && v.ValueKind == JsonValueKind.String ? v.GetString() ?? "" : "";
                    var kws = doc.RootElement.TryGetProperty("uniqueKeywords", out var k) && k.ValueKind == JsonValueKind.Array
                        ? k.EnumerateArray().Select(x => x.ValueKind == JsonValueKind.String ? x.GetString() ?? "" : "").ToArray()
                        : [];
                    entries.Add(new Entry(Path.GetFileName(vdir), Path.GetFileName(sdir),
                        Str(src, "filename"), Str(src, "hash").ToLowerInvariant(), kws));
                }
                catch (Exception ex) when (ex is IOException or JsonException or KeyNotFoundException or InvalidOperationException)
                {
                    Console.Error.WriteLine($"skipped {path}: {ex.Message}");
                }
            }
        return entries;
    }

    static string Render(List<Entry> entries, string ns, string cls)
    {
        var lines = new List<string>
        {
            "// <auto-generated>",
            "// Generated by Resonator.ShadersReferenceBuilder (meta) from <tree>/<version>/<Shader>/metadata.json.",
            "// Do not edit; re-run the generator.",
            "// </auto-generated>",
            "using System;",
            "",
            "namespace " + ns,
            "{",
            "\tpublic static partial class " + cls,
            "\t{",
            $"\t\t// {entries.Count} shader version(s)",
            "\t\tstatic partial void AddGeneratedMeta(Action<string, string, string, string, string[]> add)",
            "\t\t{",
        };
        foreach (var e in entries)
        {
            string kws = e.Keywords.Length > 0 ? "new string[] { " + string.Join(", ", e.Keywords.Select(Cs)) + " }" : "new string[0]";
            lines.Add($"\t\t\tadd({Cs(e.Version)}, {Cs(e.Shader)}, {Cs(e.File)}, {Cs(e.Hash)}, {kws});");
        }
        lines.AddRange(["\t\t}", "\t}", "}", ""]);
        return string.Join("\n", lines);
    }

    /// <summary>a C# regular string literal, escaped like Python's json.dumps(s, ensure_ascii=True)</summary>
    static string Cs(string s)
    {
        var sb = new StringBuilder("\"");
        foreach (char c in s)
            sb.Append(c switch
            {
                '"' => "\\\"", '\\' => "\\\\", '\n' => "\\n", '\r' => "\\r", '\t' => "\\t", '\b' => "\\b", '\f' => "\\f",
                _ when c < 0x20 || c > 0x7e => "\\u" + ((int)c).ToString("x4"),
                _ => c.ToString(),
            });
        return sb.Append('"').ToString();
    }
}
